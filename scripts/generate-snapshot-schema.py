#!/usr/bin/env python3
"""Generate/check the live wire schema. A C field change must receive an explicit codec review."""
import argparse
import hashlib
import json
from pathlib import Path
import subprocess
import tempfile

from pycparser import c_ast, c_generator, c_parser

ROOT = Path(__file__).resolve().parents[1]
CONFIG = json.loads((ROOT / "scripts/snapshot-fields.json").read_text())
KINDS = {"uint8_t": "SW_U8", "uint16_t": "SW_U16", "uint32_t": "SW_U32",
         "uint64_t": "SW_U64", "int32_t": "SW_I32", "int": "SW_I32",
         "unsigned": "SW_U32", "size_t": "SW_SIZE", "_Bool": "SW_BOOL",
         "float": "SW_FLOAT", "double": "SW_DOUBLE"}
LIMITS = {"SW_FLOAT": ("-1e15", "1e15"), "SW_DOUBLE": ("-1e15", "1e15"),
          "SW_I32": ("INT32_MIN", "INT32_MAX"), "SW_U32": ("0", "UINT32_MAX"),
          "SW_U16": ("0", "UINT16_MAX"), "SW_U8": ("0", "UINT8_MAX"), "SW_BOOL": ("0", "1")}
EXPORTED = {"Game": "game", "Box": "box", "RoomRecord": "room_record",
            "MatrixRecord": "matrix_record", "FactionRegion": "faction_region"}


def generate(compiler):
    with tempfile.TemporaryDirectory(prefix="sc-schema-") as directory:
        fake = Path(directory)
        (fake / "stdint.h").write_text("typedef unsigned char uint8_t;\n"
            "typedef unsigned short uint16_t; typedef unsigned int uint32_t;\n"
            "typedef unsigned long long uint64_t; typedef int int32_t;\n")
        (fake / "stdbool.h").write_text("#define bool _Bool\n#define true 1\n#define false 0\n")
        (fake / "stddef.h").write_text("typedef unsigned long size_t;\n")
        (fake / "math.h").write_text("")
        source = subprocess.check_output([compiler, "-E", "-P", "-I" + str(fake),
            "-I" + str(ROOT / "src"), str(ROOT / "src/game.h")], text=True)
    tree = c_parser.CParser().parse(source)
    types = {node.name: node.type.type for node in tree.ext if isinstance(node, c_ast.Typedef)}
    seen, blocks, metadata, referenced = set(), [], {}, set()
    printer = c_generator.CGenerator()

    def build(name):
        if name in seen:
            return
        seen.add(name)
        entries, signature = [], []
        for member in types[name].decls:
            if member.name in CONFIG["exclude"].get(name, []):
                continue
            node, dimensions = member.type, []
            while isinstance(node, c_ast.ArrayDecl):
                dimensions.append(printer.visit(node.dim))
                node = node.type
            if not isinstance(node, c_ast.TypeDecl) or not isinstance(node.type, c_ast.IdentifierType):
                raise ValueError(f"Explicit wire ownership required: {name}.{member.name}")
            typename = " ".join(node.type.names)
            child = "NULL"
            if typename in KINDS:
                kind = KINDS[typename]
                low, high = LIMITS.get(kind, ("0", "0"))
            elif isinstance(types[typename], c_ast.Enum):
                kind, low = "SW_I32", "0"
                high = CONFIG["enumlimit"].get(typename, types[typename].values.enumerators[-1].name)
            else:
                build(typename)
                referenced.add(typename)
                kind, low, high, child = "SW_STRUCT", "0", "0", "&schema_" + typename
            low, high = CONFIG["limits"].get(name + "." + member.name, (low, high))
            entries.append(f"    FIELD({name}, {member.name}, {typename}, {kind}, {child}, {low}, {high}),")
            signature.append((member.name, typename, dimensions, low, high))
        metadata[name] = signature
        blocks.append((name, "static const SnapshotField fields_" + name + "[] = {\n" +
                       "\n".join(entries) + "\n};\n"))

    for name in EXPORTED:
        build(name)
    fingerprint = int(hashlib.sha256(json.dumps(metadata, sort_keys=True).encode()).hexdigest()[:8], 16)
    result = '''/* Generated by scripts/generate-snapshot-schema.py. Explicit field order is the wire contract.
   The schema fingerprint rejects incompatible layouts; no C padding or pointers are encoded. */
// clang-format off
#include "snapshot_internal.h"
#include <limits.h>
#define FIELD(type, member, scalar, kind, child, low, high) \\
    {offsetof(type, member), sizeof(((type *)0)->member) / sizeof(scalar), sizeof(scalar), kind, child, low, high}
#define SCHEMA(name) {fields_##name, sizeof(fields_##name) / sizeof(*fields_##name)}
'''
    for name, block in blocks:
        result += block
        if name in referenced:
            result += f"static const SnapshotSchema schema_{name} = SCHEMA({name});\n"
        result += "\n"
    for name, label in EXPORTED.items():
        result += f"const SnapshotSchema sc_snapshot_{label} = SCHEMA({name});\n"
    result += f"const uint32_t sc_snapshot_schema_id = UINT32_C(0x{fingerprint:08x});\n"
    result += "#undef FIELD\n#undef SCHEMA\n// clang-format on\n"
    return result


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--cc", default="cc", help="Native C preprocessor executable")
    args = parser.parse_args()
    target = ROOT / "src/snapshot_schema.c"
    generated = generate(args.cc)
    if args.check:
        if target.read_text() != generated:
            raise SystemExit("Live snapshot fields changed. Review ownership/bounds, then regenerate the schema.")
        print("PASS: complete, current live snapshot schema")
    else:
        target.write_text(generated)


if __name__ == "__main__":
    main()
